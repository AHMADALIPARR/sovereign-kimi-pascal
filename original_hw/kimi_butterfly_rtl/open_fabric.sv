module open_fabric(input logic clk,input logic rst, input logic valid_i, output logic ready_o, input logic [255:0] data_i, output logic valid_o, output logic [255:0] data_o);
always_ff @(posedge clk) begin if(rst) begin valid_o<=1'b0; data_o<='0; end else if(valid_i && ready_o) begin data_o<=data_i; valid_o<=1'b1; end else valid_o<=1'b0; end
assign ready_o=1'b1;
endmodule
